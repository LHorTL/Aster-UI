function normalizeBrandKey(keyOrName: string): string {
  const k = keyOrName.trim().toLowerCase();
  if (BRANDS[k]) return k;
  if (k === "google drive") return "gdrive";
  if (k === "google calendar") return "gcal";
  if (k === "google analytics") return "ga";
  return k.replace(/[^a-z0-9]/g, "");
}

/** Bare vector brand mark (used in CRM company rows). */
export function BrandGlyph({
  brand,
  size = 15,
  onTile = false,
}: {
  brand: string;
  size?: number;
  onTile?: boolean;
}) {
  const key = normalizeBrandKey(brand);
  const def = BRANDS[key];
  if (!def) {
    return (
      <span
        style={{
          display: "inline-flex",
          alignItems: "center",
          justifyContent: "center",
          width: size,
          height: size,
          borderRadius: 4,
          background: "var(--af-selected)",
          color: "var(--af-page-strong)",
          fontSize: Math.max(9, Math.round(size * 0.65)),
          fontWeight: 680,
          flex: "none",
        }}
        aria-hidden="true"
      >
        {brand.charAt(0).toUpperCase()}
      </span>
    );
  }
  const defaultFill = onTile && def.tileFg ? def.tileFg : (def.glyphFill ?? "currentColor");
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={defaultFill}
      style={{ flex: "none", display: "block" }}
      aria-hidden="true"
    >
      {def.paths.map((p, idx) => (
        <path key={idx} d={p.d} fill={onTile && def.tileFg ? def.tileFg : p.fill} />
      ))}
    </svg>
  );
}

/** Rounded-square brand app icon tile (used in Integrations & CRM view tabs). */
export function BrandAppTile({
  brand,
  size = 30,
  radius = 8,
  glyphSize,
  style,
}: {
  brand: string;
  size?: number;
  radius?: number;
  glyphSize?: number;
  style?: CSSProperties;
}) {
  const key = normalizeBrandKey(brand);
  const def = BRANDS[key];
  const hasSolidTile = Boolean(def?.tileBg);
  const isLightTile = def?.tileBg === "#ffffff";
  const iconPx = glyphSize ?? Math.round(size * 0.54);

  return (
    <span
      style={{
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        width: size,
        height: size,
        borderRadius: radius,
        background: def?.tileBg ?? "var(--af-surface)",
        color: def?.tileFg ?? "var(--af-page-strong)",
        boxShadow: isLightTile
          ? "0 0 0 0.5px rgba(0,0,0,0.12), 0 1px 2px rgba(0,0,0,0.08)"
          : hasSolidTile
            ? "inset 0 0 0 0.5px rgba(255,255,255,0.14)"
            : "var(--af-shadow-hairline)",
        flex: "none",
        ...style,
      }}
      aria-hidden="true"
    >
      <BrandGlyph brand={key} size={iconPx} onTile={hasSolidTile} />
    </span>
  );
}
